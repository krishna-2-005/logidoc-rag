import { AlertTriangle, Bot, CheckCircle2, HelpCircle, ShieldAlert, Send, Wrench } from "lucide-react"
import { useState, type FormEvent } from "react"
import { PageHeader } from "@/components/common/PageHeader"
import { errorMessage } from "@/components/common/states"
import { Alert } from "@/components/ui/alert"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import { Card } from "@/components/ui/card"
import { Input, Label, Select } from "@/components/ui/input"
import { useAssistant, useShipments } from "@/hooks/queries"
import type { AssistantReply } from "@/lib/types"

const SUGGESTIONS = ["Give me a status summary", "How many pieces were delivered?", "Was the delivery late?", "What is the invoice total?", "Which documents are missing?", "What is the financial exposure?"]

const STATUS = {
  answered: { tone: "ok", text: "Answered from the audit", icon: <CheckCircle2 /> },
  insufficient_evidence: { tone: "warn", text: "Insufficient evidence", icon: <AlertTriangle /> },
  clarification: { tone: "info", text: "Needs clarification", icon: <HelpCircle /> },
  refused: { tone: "bad", text: "Refused", icon: <ShieldAlert /> },
} as const

interface Turn {
  question: string
  reply?: AssistantReply
  error?: string
}

export function ReplyView({ reply }: { reply: AssistantReply }) {
  const look = STATUS[reply.status]

  return (
    <div className="space-y-3" data-testid="assistant-reply">
      <Badge tone={look.tone}>
        <span aria-hidden="true">{look.icon}</span> {look.text}
      </Badge>
      {reply.generated && <Alert tone="warn"><p>Generated by a language model from the shipment's documents. It is not a verified audit finding.</p></Alert>}
      <p className="whitespace-pre-wrap text-sm">{reply.answer}</p>

      {reply.findings.length > 0 && (
        <dl className="divide-y rounded-md border text-sm">
          {reply.findings.map((finding, index) => (
            <div key={index} className="flex justify-between gap-4 px-3 py-1.5">
              <dt className="text-muted-foreground">{finding.label}</dt>
              <dd className="tabular text-right">{String(finding.value ?? "not available")} <span className="text-xs text-muted-foreground">({finding.status})</span></dd>
            </div>
          ))}
        </dl>
      )}

      {reply.uncertainty.length > 0 && (
        <div className="rounded-md bg-warn-soft p-3 text-xs text-warn">
          <p className="font-semibold">Uncertainty</p>
          <ul className="mt-1 list-disc pl-4">{reply.uncertainty.map((item) => <li key={item}>{item}</li>)}</ul>
        </div>
      )}

      {reply.citations.length > 0 && (
        <details className="text-xs" open>
          <summary className="cursor-pointer font-medium text-primary">Sources ({reply.citations.length})</summary>
          <ul className="mt-2 space-y-1.5">
            {reply.citations.map((c, index) => (
              <li key={index} className="rounded bg-muted/70 px-2.5 py-1.5">
                <span className="font-medium">{c.source}{c.page ? ` · p.${c.page}` : ""} · {c.document_type}</span>
                {c.text && <span className="block text-muted-foreground">{c.text}</span>}
              </li>
            ))}
          </ul>
        </details>
      )}

      {reply.next_steps.length > 0 && (
        <div className="text-xs">
          <p className="font-semibold">Suggested next steps</p>
          <ul className="mt-1 list-disc pl-4">{reply.next_steps.map((item) => <li key={item}>{item}</li>)}</ul>
          <p className="mt-1 text-muted-foreground">The assistant never acts on these: a person decides and approves.</p>
        </div>
      )}

      {reply.tools_used.length > 0 && (
        <p className="flex flex-wrap items-center gap-1.5 text-xs text-muted-foreground">
          <Wrench className="size-3" aria-hidden="true" /> Read-only tools used:
          {[...new Set(reply.tools_used.map((tool) => tool.name))].map((name) => <Badge key={name}>{name}</Badge>)}
        </p>
      )}
    </div>
  )
}

export function Assistant() {
  const shipments = useShipments({})
  const ask = useAssistant()
  const [scope, setScope] = useState("")
  const [question, setQuestion] = useState("")
  const [turns, setTurns] = useState<Turn[]>([])

  const send = (text: string) => {
    const q = text.trim()
    if (!q || ask.isPending) return

    setQuestion("")
    setTurns((current) => [...current, { question: q }])

    ask.mutate(
      { question: q, shipment_id: scope || undefined },
      {
        onSuccess: (reply) => setTurns((current) => current.map((turn, i) => (i === current.length - 1 ? { ...turn, reply } : turn))),
        onError: (error) => setTurns((current) => current.map((turn, i) => (i === current.length - 1 ? { ...turn, error: errorMessage(error) } : turn))),
      },
    )
  }

  const submit = (event: FormEvent) => {
    event.preventDefault()
    send(question)
  }

  return (
    <>
      <PageHeader title="AI Assistant" description="Ask about one shipment. Answers come from the audit through read-only tools, with their sources. The assistant cannot change anything, and it says so when the evidence is not enough." />

      <div className="mb-4 max-w-sm space-y-1.5">
        <Label htmlFor="assistant-scope">Shipment</Label>
        <Select id="assistant-scope" value={scope} onChange={(event) => { setScope(event.target.value); setTurns([]) }}>
          <option value="">Choose or name it in the question</option>
          {shipments.data?.shipments.map((row) => <option key={row.shipment_key} value={row.shipment_id}>{row.shipment_id}</option>)}
        </Select>
      </div>

      <div className="space-y-4" aria-live="polite">
        {turns.length === 0 && (
          <Card className="p-5">
            <p className="mb-3 flex items-center gap-2 text-sm font-medium"><Bot className="size-4" aria-hidden="true" /> Try one of these</p>
            <div className="flex flex-wrap gap-2">
              {SUGGESTIONS.map((text) => <Button key={text} variant="outline" size="sm" onClick={() => send(text)}>{text}</Button>)}
            </div>
          </Card>
        )}

        {turns.map((turn, index) => (
          <div key={index} className="space-y-2">
            <p className="ml-auto w-fit max-w-xl rounded-lg bg-primary px-3.5 py-2 text-sm text-primary-foreground">{turn.question}</p>
            <Card className="p-4">
              {turn.reply ? <ReplyView reply={turn.reply} /> : turn.error ? <Alert tone="bad">{turn.error}</Alert> : <p className="text-sm text-muted-foreground">Reading the audit…</p>}
            </Card>
          </div>
        ))}
      </div>

      <form onSubmit={submit} className="sticky bottom-0 mt-6 flex gap-2 bg-background py-3">
        <Label htmlFor="assistant-question" className="sr-only">Your question</Label>
        <Input id="assistant-question" value={question} maxLength={1000} onChange={(event) => setQuestion(event.target.value)} placeholder="e.g. How many pieces were short?" />
        <Button type="submit" disabled={ask.isPending || !question.trim()}><Send /> Ask</Button>
      </form>
    </>
  )
}
